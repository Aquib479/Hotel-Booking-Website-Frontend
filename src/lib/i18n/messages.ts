export type MessageKey = keyof typeof M;

export function hasMessage(key: string): boolean {
  return Object.prototype.hasOwnProperty.call(M, key);
}

export function translate(
  language: AppLanguage,
  key: string,
  vars?: Record<string, string | number>,
): string {
  const pair = (M as Record<string, MessagePair | undefined>)[key];
  let text = pair?.[language] ?? pair?.en ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      text = text.replaceAll(`{${k}}`, String(v));
    }
  }
  return text;
}

/** Translate `key` or `key|value` stored strings; otherwise return the original (API) text. */
export function translateStored(
  language: AppLanguage,
  stored: string,
  extraVars?: Record<string, string | number>,
): string {
  const i = stored.indexOf("|");
  const key = i === -1 ? stored : stored.slice(0, i);
  const val = i === -1 ? undefined : stored.slice(i + 1);
  if (!hasMessage(key)) return stored;
  return translate(language, key, {
    ...(val !== undefined ? { n: val, list: val, source: val, name: val, city: val } : {}),
    ...extraVars,
  });
}
